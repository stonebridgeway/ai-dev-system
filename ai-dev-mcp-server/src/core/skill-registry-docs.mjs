/**
 * The generated skill registries: where they live and what their Markdown
 * companions look like.
 *
 * `rebuild_index` (src/extensions/skills.mjs) collects skills from the vault,
 * classifies them and writes these files; `rebuild_skill_taxonomy` rewrites the
 * JSON half of the same set. Both name the files from `SKILL_REGISTRY_FILES` so
 * the two paths cannot drift. The renders below take arrays that are already
 * collected and classified, so they stay testable without a vault.
 */
import { SKILL_CATALOG_DIR } from "./skill-catalog.mjs";
import { markdownTable, shorten } from "./text-format.mjs";

const registriesDir = `${SKILL_CATALOG_DIR}/registries`;

/** Vault-relative paths of every file `rebuild_index` regenerates. */
export const SKILL_REGISTRY_FILES = Object.freeze({
  combined: `${registriesDir}/skills.index.json`,
  custom: `${registriesDir}/custom.skills.index.json`,
  design: `${registriesDir}/design.skills.index.json`,
  membrane: `${registriesDir}/membrane.skills.index.json`,
  external: `${registriesDir}/external.skills.index.json`,
  names: `${registriesDir}/skills.names.txt`,
  customMarkdown: `${registriesDir}/CUSTOM_WORKFLOW_SKILLS.md`,
  designMarkdown: `${registriesDir}/DESIGN_TASTE_SKILLS.md`,
  membraneMarkdown: `${registriesDir}/ALL_MEMBRANE_SKILLS.md`,
  externalMarkdown: `${registriesDir}/EXTERNAL_SKILLS.md`
});

/** Newline-terminated list of every registered skill name, one per line. */
export function renderSkillNames(combined) {
  return `${combined.map((item) => item.name).join("\n")}\n`;
}

/** Markdown index of the custom workflow skills. */
export function renderCustomSkillsMarkdown(custom) {
  return markdownTable("Custom Workflow Skills", custom, [
    { title: "Skill", value: (item) => item.name },
    { title: "Use when", value: (item) => shorten(item.use_when, 220) },
    { title: "File", value: (item) => `\`${item.path}\`` }
  ]);
}

/** Markdown index of the design-oriented skills. */
export function renderDesignSkillsMarkdown(design) {
  return [
    "# Design Skills",
    "",
    "Autogenerated index of design-oriented skills.",
    "",
    markdownTable("Design Taste Skills", design, [
      { title: "Skill", value: (item) => item.name },
      { title: "Source", value: (item) => item.source },
      { title: "Type", value: (item) => item.type },
      { title: "Use when", value: (item) => shorten(item.use_when, 220) },
      { title: "File", value: (item) => `\`${item.path}\`` }
    ])
  ].join("\n");
}

/** Markdown index of the Membrane application skills. */
export function renderMembraneSkillsMarkdown(membrane) {
  return [
    "# All Membrane Skills",
    "",
    "Autogenerated index of all Membrane application skills currently stored in this vault.",
    "",
    `Total skills: ${membrane.length}`,
    "",
    markdownTable("Membrane Skills", membrane, [
      { title: "Skill", value: (item) => item.name },
      { title: "Subgroup", value: (item) => (item.subgroups || []).join(", ") },
      { title: "Use when", value: (item) => shorten(item.use_when, 180) },
      { title: "File", value: (item) => `\`${item.path}\`` }
    ])
  ].join("\n");
}

/** Markdown index of the imported external skills. */
export function renderExternalSkillsMarkdown(external) {
  return markdownTable("External Imported Skills", external, [
    { title: "Skill", value: (item) => item.name },
    { title: "Source", value: (item) => item.source },
    { title: "Use when", value: (item) => shorten(item.use_when, 220) },
    { title: "File", value: (item) => `\`${item.path}\`` }
  ]);
}

/**
 * Shape the `rebuild_index` response from the counts and paths of the run.
 *
 * @param {object} input
 * @param {object[]} input.custom
 * @param {object[]} input.design
 * @param {object[]} input.external
 * @param {object[]} input.membrane
 * @param {object[]} input.combined
 * @param {object} input.taxonomy - Result of writing the taxonomy artifacts.
 * @param {object} input.skillCards - Result of the card sync.
 * @param {{ skillGroupsIndex: string, skillGraphIndex: string, skillsMap: string }} input.paths
 * @returns {object}
 */
export function buildRebuildIndexReport({
  custom, design, external, membrane, combined, taxonomy, skillCards, paths
}) {
  return {
    total: combined.length,
    custom: custom.length,
    design: design.length,
    external: external.length,
    membrane: membrane.length,
    skill_cards: skillCards.total,
    taxonomy_schema_version: taxonomy.schema_version,
    skill_groups: taxonomy.groups.map((group) => ({ id: group.id, count: group.count })),
    visual_graph: {
      linked_unique_skills: taxonomy.visual_graph.linked_unique_skills,
      batch_pages: taxonomy.visual_graph.batch_pages,
      group_hubs: taxonomy.visual_graph.group_hubs,
      bucket_hubs: taxonomy.visual_graph.bucket_hubs,
      page_size: taxonomy.visual_graph.page_size
    },
    files: {
      combined: SKILL_REGISTRY_FILES.combined,
      names: SKILL_REGISTRY_FILES.names,
      custom: SKILL_REGISTRY_FILES.customMarkdown,
      design: SKILL_REGISTRY_FILES.designMarkdown,
      external: SKILL_REGISTRY_FILES.externalMarkdown,
      membrane: SKILL_REGISTRY_FILES.membraneMarkdown,
      skill_groups_index: paths.skillGroupsIndex,
      skill_graph_index: paths.skillGraphIndex,
      skills_map: paths.skillsMap,
      complete_skill_graph: taxonomy.visual_graph.root_note,
      skill_cards_index: skillCards.index_path,
      skill_cards_catalog: skillCards.catalog_path
    }
  };
}
