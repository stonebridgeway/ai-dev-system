#!/usr/bin/env node
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { legacyTools } from "../src/mcp-stdio.mjs";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const serverRoot = path.resolve(scriptDir, "..");
const outputPath = path.join(serverRoot, "docs", "TOOLS.md");

function schemaSummary(schema = {}) {
  const properties = Object.entries(schema.properties || {});
  if (!properties.length) return "No arguments.";
  return properties.map(([name, value]) => {
    const required = schema.required?.includes(name) ? "required" : "optional";
    const type = value.enum ? `enum: ${value.enum.join(" | ")}` : value.type || "value";
    return `- \`${name}\` (${required}, ${type})${value.description ? ` — ${value.description}` : ""}`;
  }).join("\n");
}

function render() {
  const tools = [...legacyTools].sort((left, right) => left.name.localeCompare(right.name));
  const lines = [
    "# Tool reference",
    "",
    "> Generated by `npm run docs:tools`; edit `src/tool-definitions.mjs` instead.",
    "",
    `Legacy compatibility surface: **${tools.length} tools**. The default \`core\` profile exposes a smaller grouped surface; use \`AI_DEV_TOOL_PROFILE=full\` for these legacy names.`,
    ""
  ];
  for (const tool of tools) {
    lines.push(`## \`${tool.name}\``, "", tool.description || "No description.", "", schemaSummary(tool.inputSchema), "");
  }
  return `${lines.join("\n").trim()}\n`;
}

const output = render();
if (process.argv.includes("--check")) {
  const current = await fs.readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    process.stderr.write(`Generated tool reference is stale: ${outputPath}\n`);
    process.exitCode = 1;
  }
} else {
  await fs.writeFile(outputPath, output, "utf8");
}

export { render };
