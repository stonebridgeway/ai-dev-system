/**
 * `docs/CONTROL-API.md` from the control tools themselves: their inputs from
 * the definitions, their answers from `src/core/control-contract.mjs`, the
 * same schemas the server hands a client. `render-tool-reference.mjs` writes
 * and checks it together with `docs/TOOLS.md`, so neither can drift.
 */
import { CONTROL_API_VERSION, CONTROL_RESULTS, CONTROL_TOOLS } from "../src/core/control-contract.mjs";

/** A schema's type as a reader says it. */
function typeOf(schema = {}) {
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(" or ");
  if (schema.enum) return schema.enum.map((value) => `\`${JSON.stringify(value)}\``).join(", ");
  if (schema.type === "array") return schema.items?.type === "object" ? "array of objects" : `array of ${typeOf(schema.items)}`;
  if (schema.type === "integer") return "integer";
  return schema.type ?? "any";
}

/** The fields of an object schema as nested list lines. */
function fields(schema, depth = 0) {
  const lines = [];
  const required = new Set(schema.required ?? []);
  for (const [name, property] of Object.entries(schema.properties ?? {})) {
    const nested = property.type === "object" && property.properties ? property
      : property.type === "array" && property.items?.type === "object" && property.items.properties ? property.items
        : property.anyOf?.find((option) => option.type === "object" && option.properties) ?? null;
    const sentence = (text) => (text && !/[.!?]$/.test(text) ? `${text}.` : text);
    const note = [sentence(property.description), property.default !== undefined ? `Default \`${JSON.stringify(property.default)}\`.` : ""].filter(Boolean).join(" ");
    const kind = nested && property.type === "array" ? "array of objects" : nested ? (property.anyOf ? `${typeOf({ anyOf: property.anyOf.filter((option) => option !== nested) })} or object` : "object") : typeOf(property);
    lines.push(`${"  ".repeat(depth)}- \`${name}\` — ${kind}${required.has(name) ? "" : ", optional"}${note ? `. ${note}` : ""}`);
    if (nested) lines.push(...fields(nested, depth + 1));
  }
  return lines;
}

/**
 * @param {Array<{ name: string, description: string, inputSchema: object, annotations?: object }>} definitions - The control tools' definitions.
 * @param {Set<string>} readOnly
 * @returns {string}
 */
export function renderControlApi(definitions, readOnly) {
  const byName = new Map(definitions.map((definition) => [definition.name, definition]));
  const lines = [
    "# Control API",
    "",
    "<!-- Generated by scripts/render-control-api.mjs through scripts/render-tool-reference.mjs; do not edit by hand. -->",
    "",
    `Version **${CONTROL_API_VERSION}**. The tools a desktop app — or a script — drives AI Dev with: the state of the`,
    "install, setting it up, the local model, the AI clients connected to it, its logs, its settings, and an overview",
    "of the work. They are MCP tools like the others, served by the same daemon, and they make up the `control`",
    "profile, which is opt-in: a session lists them only when it names it (`AI_DEV_PROFILES=control`, alone or with",
    "others). A client that knows a tool's name can call it in any session.",
    "",
    "## Connecting",
    "",
    "- From a program: `DaemonClientTransport` (`src/core/daemon-transport.mjs`) with the MCP SDK's `Client` finds",
    "  or starts the daemon of the install and proves itself with the descriptor's secret; `profiles: \"control\"`",
    "  lists these tools. The session runs in the environment the transport is given, as a client's does.",
    "- From a client config: `ai-dev mcp` with `AI_DEV_PROFILES=control` in its environment.",
    "",
    "## Conventions",
    "",
    "- **Answers.** Every answer is JSON in the text content and, the same, in `structuredContent.result`. Each tool",
    "  advertises the schema below as its `outputSchema`, so an MCP SDK client checks every answer against it.",
    "- **Versions.** `system_status` answers `api_version`. A new optional field, a new tool or a new value of an",
    "  open string is a minor change; a removed, retyped or newly required field is a major one. Objects may carry",
    "  fields this document does not list: read the ones you know.",
    "- **Errors.** A refused call — a wrong argument, a missing `confirm` — answers `isError: true` with the reason",
    "  as its text, and changes nothing. An unknown argument is refused, not ignored.",
    "- **Progress and cancelling.** The long tools (`setup_run`, `model_install`, `model_import`, `model_verify`)",
    "  send `notifications/progress` when the request carries a `progressToken`, and stop when the client cancels",
    "  the request: what is done is kept (a download continues next time from where it stopped).",
    "- **Read-only and destructive.** Each tool's MCP annotations say so; the list below too.",
    ""
  ];
  for (const name of CONTROL_TOOLS) {
    const definition = byName.get(name);
    if (!definition) throw new Error(`The contract names ${name}, which the server does not define.`);
    const marks = [readOnly.has(name) ? "read-only" : "", definition.annotations?.destructiveHint ? "destructive" : ""].filter(Boolean);
    lines.push(`## \`${name}\`${marks.length ? ` (${marks.join(", ")})` : ""}`, "", definition.description, "");
    const input = fields(definition.inputSchema);
    lines.push("**Input:**", "", ...(input.length ? input : ["No arguments."]), "");
    lines.push("**Answer** (`structuredContent.result`):", "", ...fields(CONTROL_RESULTS[name]), "");
  }
  const extra = definitions.map((definition) => definition.name).filter((name) => !CONTROL_TOOLS.includes(name));
  if (extra.length) throw new Error(`Control tools without a contract: ${extra.join(", ")}.`);
  return `${lines.join("\n").trimEnd()}\n`;
}
